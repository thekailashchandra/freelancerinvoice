const fs = require("fs");
const path = require("path");

const buildId = String(Date.now());
const rootDir = path.join(__dirname, "..");
const publicDir = path.join(rootDir, "public");
const outFile = path.join(publicDir, "dev-build.json");
const clientIdFile = path.join(rootDir, "lib", "dev-build-id.generated.ts");

if (!fs.existsSync(publicDir)) {
  fs.mkdirSync(publicDir, { recursive: true });
}

fs.writeFileSync(outFile, JSON.stringify({ buildId }), "utf8");
fs.writeFileSync(
  clientIdFile,
  `/** Auto-generated by scripts/write-dev-build-id.js — do not edit. */\nexport const CLIENT_DEV_BUILD_ID = ${JSON.stringify(buildId)};\n`,
  "utf8"
);
console.log(`Dev build id: ${buildId}`);
